'use strict';
// Run using VS Code --extensionTestsPath=<this file> under a disposable profile.
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const vscode = require('vscode');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
exports.run = async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dream-vscode-'));
  const main = path.join(dir, 'main.cpp');
  const header = path.join(dir, 'shared.hpp');
  fs.writeFileSync(main, 'int main() {\n  volatile int value = 1;\n  return value - 1;\n}\n');
  fs.writeFileSync(header, 'int shared = 1;\n');
  const config = vscode.workspace.getConfiguration('dreamCppDebug');
  await config.update('interfaceMode', 'beginner', vscode.ConfigurationTarget.Global);
  const doc = await vscode.workspace.openTextDocument(main);
  let editor = await vscode.window.showTextDocument(doc, { preview: false });
  await vscode.extensions.getExtension('wudream.dream-cpp-debuger').activate();
  await vscode.commands.executeCommand('dream-cpp-debug.startDebug');
  await vscode.window.showTextDocument(doc, { preview: false });
  await wait(200);
  let before = doc.getText();
  await vscode.commands.executeCommand('type', { text: 'Z' });
  assert.strictEqual(doc.getText(), before, 'typing into source must be blocked during debugging');
  const headerDoc = await vscode.workspace.openTextDocument(header);
  await vscode.window.showTextDocument(headerDoc, { preview: false });
  await wait(200);
  before = headerDoc.getText();
  await vscode.commands.executeCommand('type', { text: 'Z' });
  assert.strictEqual(headerDoc.getText(), before, 'switching source editors must apply protection');
  await vscode.commands.executeCommand('dream-cpp-debug.stop');
  await vscode.window.showTextDocument(doc, { preview: false });
  await vscode.commands.executeCommand('type', { text: 'Z' });
  assert.notStrictEqual(doc.getText(), 'int main() {\n  volatile int value = 1;\n  return value - 1;\n}\n', 'source must be editable after stop');
  await vscode.commands.executeCommand('undo');
  await vscode.window.showTextDocument(headerDoc, { preview: false });
  await vscode.commands.executeCommand('type', { text: 'Z' });
  assert.notStrictEqual(headerDoc.getText(), 'int shared = 1;\n', 'other source must be editable after stop');
  await vscode.commands.executeCommand('undo');
  editor = await vscode.window.showTextDocument(doc, { preview: false });
  await editor.edit(edit => edit.insert(new vscode.Position(0, 0), 'this is invalid C++\n'));
  await doc.save();
  await vscode.commands.executeCommand('dream-cpp-debug.startDebug');
  await vscode.window.showTextDocument(doc, { preview: false });
  before = doc.getText();
  await vscode.commands.executeCommand('type', { text: 'Z' });
  assert.notStrictEqual(doc.getText(), before, 'compile failure must restore editing');
  console.log('REAL_VSCODE_READONLY_PASS');
  fs.rmSync(dir, { recursive: true, force: true });
};
